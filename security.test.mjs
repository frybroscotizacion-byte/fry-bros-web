import assert from 'node:assert/strict';
import worker,{validarPayload} from './worker.mjs';
const p={servicioId:'papas',personas:40,nombre:'Prueba',whatsapp:'12345678',tipoEvento:'Otro evento',fechaEvento:'2099-12-31',comuna:'Comuna',direccion:'Direccion'};
for(const v of [null,[],true,1,'x'])assert.ok(validarPayload(v).error);
assert.ok(validarPayload({...p,fechaEvento:'2099-02-31'}).error);
assert.ok(validarPayload(p).datos);
let calls=[];
const env={GOOGLE_SHEETS_WEBHOOK_URL:'https://script.google.com/macros/s/mock/exec',FRY_BROS_SECRET:'local',TURNSTILE_SECRET_KEY:'local',QUOTE_RATE_LIMITER:{limit:async()=>({success:true})}};
globalThis.fetch=async(url,options)=>{calls.push([url,JSON.parse(options.body)]);return Response.json(url.includes('siteverify')?{success:true,hostname:'local.invalid',action:'quote'}:{success:true});};
const req=(body,origin='https://local.invalid')=>new Request('https://local.invalid/api/cotizaciones',{method:'POST',headers:{Origin:origin,'Content-Type':'application/json'},body:JSON.stringify(body)});
assert.equal((await worker.fetch(req(null),env)).status,400);
assert.equal((await worker.fetch(req(p,'https://other.invalid'),env)).status,403);
assert.equal((await worker.fetch(req(p),{...env,QUOTE_RATE_LIMITER:undefined})).status,503);
assert.equal((await worker.fetch(req(p),{...env,QUOTE_RATE_LIMITER:{limit:async()=>({success:false})}})).status,429);
assert.equal((await worker.fetch(req({...p,nombre:'=formula',turnstileToken:'mock'}),env)).status,200);
assert.equal(calls.at(-1)[1].nombre,"'=formula");
assert.notEqual(calls.at(-1)[1].cotizacion,1);
globalThis.fetch=async()=>Response.json({success:false});
assert.equal((await worker.fetch(req({...p,turnstileToken:'bad'}),env)).status,403);
console.log('Public security tests passed');
